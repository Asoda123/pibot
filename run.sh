#!/bin/bash

# Ця команда видаляє старий файл блокування
# Якщо контейнер був некоректно зупинений
rm -f /tmp/.X99-lock

# Запускаємо Xvfb у фоновому режимі на дисплеї :99
Xvfb :99 -screen 0 1024x768x24 &

# Встановлюємо змінну оточення DISPLAY
export DISPLAY=:99

# Чекаємо, поки Xvfb буде доступний
# Це гарантує, що програма не запуститься, поки X-сервер не буде готовий
timeout 60 bash -c 'while ! xdpyinfo >/dev/null 2>&1; do sleep 1; done'

# Запускаємо ваш Python-скрипт
python3 main.py